// Standalone SVP runner, structured like svp_consistency_sharp_impl: "both"
// pruning is exact here for the same reason as plain "both"
// (all simultaneously alive candidates compare against the identical
// shared value gamma(t) at every step; validity is hereditary because a
// candidate's own max_cost() cannot un-fail once the SVP "both" rule has
// discarded it, by construction of the pruning rule itself).
inline Rcpp::List svp_empirical_both_impl(
    const std::vector<double>& data,
    double gamma_offset,
    double sigma2,
    const SegmentCost& segment_cost)
{
  const std::size_t n = data.size();
  if (n != EMPIRICAL_BOTH_GAMMA_TABLE.size() + 1) {
    Rcpp::stop(
      "subtests = 'both_empirical' requires data of length %d "
      "(the calibrated series length).",
      static_cast<int>(EMPIRICAL_BOTH_GAMMA_TABLE.size() + 1)
    );
  }

  std::deque<EmpiricalBothCandidate> candidates;
  candidates.emplace_back(0);
  std::vector<double> Q(n + 1, 0.0);
  std::vector<std::size_t> K(n + 1, 0), previous(n + 1, 0), nb(n, 0);

  for (std::size_t t = 1; t <= n; ++t) {
    nb[t - 1] = candidates.size();
    const double gamma_t = (t >= 2)
      ? EMPIRICAL_BOTH_GAMMA_TABLE[t - 2] + gamma_offset
      : std::numeric_limits<double>::infinity();

    std::size_t remove = 0;
    for (std::size_t j = candidates.size(); j > 0; --j) {
      auto& candidate = candidates[j - 1];
      candidate.focus.update(data[t - 1]);
      const std::size_t length = t - candidate.boundary;
      if (length > 1) {
        const double stat = candidate.focus.max_cost() / sigma2;
        if (stat > gamma_t) { remove = j; break; }
      }
    }
    while (remove > 0) { candidates.pop_front(); --remove; }

    std::size_t best_K = n + 1, best_s = 0;
    double best_Q = std::numeric_limits<double>::infinity();
    for (const auto& candidate : candidates) {
      const auto s = candidate.boundary;
      const double q = Q[s] + segment_cost(s, t);
      if (is_better_candidate(K[s] + 1, q, best_K, best_Q)) {
        best_K = K[s] + 1; best_Q = q; best_s = s;
      }
    }
    Q[t] = best_Q; K[t] = best_K; previous[t] = best_s;
    candidates.emplace_back(t);
  }

  std::vector<std::size_t> changepoints, last_index_set;
  for (std::size_t t = n; t > 0; t = previous[t]) changepoints.push_back(t);
  std::reverse(changepoints.begin(), changepoints.end());
  for (auto it = candidates.rbegin(); it != candidates.rend(); ++it)
    last_index_set.push_back(it->boundary);
  return Rcpp::List::create(
    Rcpp::Named("changepoints") = changepoints,
    Rcpp::Named("lastIndexSet") = last_index_set,
    Rcpp::Named("nb") = nb,
    Rcpp::Named("costQ") = R_NilValue,
    Rcpp::Named("R") = build_R_matrix(Q, K, previous));
}

