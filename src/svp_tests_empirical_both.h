// Time-varying "both" threshold gamma(t) = E_t + c*sqrt(V_t), fit directly
// by simulation (simulations/power_gaussian/calibrate_empirical_both.R).
// F_t = F_both(y_{0..t}) is the TRUE aggregate "both" statistic: the max
// over every sub-segment of the first t observations (both endpoints
// free), not just those ending at t (that narrower, fixed-right-endpoint
// quantity is F_left(y_{0..t}), and F_both(y_{0..t}) = running cummax of
// F_left(y_{0..b}) over b<=t -- see the calibration script for why F_both,
// not F_left, is the statistic "both" pruning's exactness actually
// requires). E_t, V_t are the simulated mean and variance of F_t, and c is
// calibrated from the empirical 99th percentile of the JOINT running max
// max_{b=2..n} (F_b - E_b)/sqrt(V_b) over one simulated null trajectory per
// replicate (not a per-length or Bonferroni approximation). Because t is
// the CURRENT TOTAL observed length -- the same value for every
// simultaneously alive candidate at that moment, exactly like a flat
// "both" threshold, just varying over time instead of being fixed once at
// t=n -- every candidate compares its own max_cost() (single-anchored
// FOCUS, unchanged -- NOT F_both itself; this remains a heuristic
// shortcut, same caveat as plain "both") against the same shared gamma(t),
// so no per-candidate bookkeeping beyond what "both" pruning already does
